"""Check the evaluation set before any model is scored against it.

For every answerable question: the gold SQL must pass the production guard,
return rows (not truncated), match the figures published by the
sql-business-analytics project where given, and, for top-N questions, not
have a tie at the cut-off. For privacy and write cases, the guard must reject
the naive SQL. Writes results/GOLD_ANSWERS.md and exits 1 on any failure.
"""
import re
import sys

from tabulate import tabulate

from sqlhelper.compare import compare
from sqlhelper.db import QueryRejected, run_query
from sqlhelper.policy import ROOT
from sqlhelper.questions import load_questions

OUT = ROOT / "results" / "GOLD_ANSWERS.md"
SHOW_ROWS = 12
LIMIT = re.compile(r"\bLIMIT\s+(\d+)\s*$", re.IGNORECASE)


def tie_at_cutoff(sql: str) -> str:
    """'tie', 'no tie', 'n/a' or 'checked by hand'. Reruns a top-N query with one more row and
    compares the last two rows on their numeric columns."""
    m = LIMIT.search(sql)
    if not m:
        return "n/a"
    k = int(m.group(1))
    rows = run_query(LIMIT.sub(f"LIMIT {k + 1}", sql)).rows
    if len(rows) <= k:
        return "no tie"
    nums = [i for i, v in enumerate(rows[k - 1]) if isinstance(v, (int, float))]
    if not nums:  # ranked by an expression that isn't selected
        return "checked by hand"
    return "tie" if all(rows[k - 1][i] == rows[k][i] for i in nums) else "no tie"


def main() -> None:
    answerable, decline = load_questions()
    problems, summary, sections = [], [], []
    for q in answerable:
        try:
            res = run_query(q.sql)
        except QueryRejected as e:
            problems.append(f"{q.id}: gold SQL rejected: {e.reason}")
            continue
        if not res.rows or res.truncated:
            problems.append(f"{q.id}: gold result is empty or truncated")
        published = "-"
        if q.published is not None:
            v = compare(q.published, res.rows, ordered=q.ordered, tolerance=q.tolerance)
            published = "matches" if v.match else f"DIFFERS ({v.detail})"
            if not v.match:
                problems.append(f"{q.id}: differs from the published figure ({v.detail})")
        tie = tie_at_cutoff(q.sql)
        if tie == "tie":
            problems.append(f"{q.id}: tie at the top-N cut-off")
        summary.append([q.id, q.area, q.level, "yes" if q.ordered else "no", len(res.rows), published, tie])
        shown = res.rows[:SHOW_ROWS]
        more = f"\n\n*{len(res.rows) - SHOW_ROWS} more rows not shown.*" if len(res.rows) > SHOW_ROWS else ""
        sections.append(f"### {q.id}. {q.question}\n\n```sql\n{q.sql}\n```\n\n"
                        f"{tabulate(shown, headers=res.columns, tablefmt='github', disable_numparse=True)}{more}\n")

    decline_rows = []
    for d in decline:
        if d.naive_sql is None:
            decline_rows.append([d.id, d.kind, d.question, "n/a (nothing to query)"])
            continue
        try:
            run_query(d.naive_sql)
            problems.append(f"{d.id}: the guard ran the naive SQL")
            outcome = "RAN"
        except QueryRejected as e:
            outcome = f"rejected: {e.reason}"
        decline_rows.append([d.id, d.kind, d.question, outcome])

    by_level = {lvl: sum(1 for q in answerable if q.level == lvl) for lvl in ("easy", "medium", "hard")}
    lines = [
        "# Gold answers", "",
        "Generated by `scripts/check_gold.py`. Don't edit by hand.", "",
        f"{len(answerable)} answerable questions ({by_level['easy']} easy, {by_level['medium']} medium, "
        f"{by_level['hard']} hard) and {len(decline)} the helper must decline. "
        f"Every gold query ran through the same guard a generated query will face.", "",
        f"**Checks: {'all passed' if not problems else f'{len(problems)} failed'}.**", "",
        "## Summary", "",
        tabulate(summary, headers=["id", "area", "level", "ordered", "rows", "published figure", "top-N tie"],
                 tablefmt="github"), "",
        "## Must decline", "",
        tabulate(decline_rows, headers=["id", "kind", "question", "guard on the naive SQL"], tablefmt="github"), "",
        "## Answers", "", *sections,
    ]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(answerable)} answerable, {len(decline)} decline cases")
    for p in problems:
        print("FAIL", p)
    sys.exit(1 if problems else 0)


if __name__ == "__main__":
    main()
